@pytest.mark.parametrize("command", CHANGES_NOTHING)
def test_a_command_that_changes_nothing_is_read_only(command):
    assert is_read_only_command(command) is True


@pytest.mark.parametrize("command", CHANGES_SOMETHING)
def test_a_command_that_changes_something_is_not_read_only(command):
    assert is_read_only_command(command) is False


@pytest.mark.parametrize("command", [None, 42, ["ls"], "", "   ", 'echo "unterminated', "ls <> f"])
def test_anything_that_is_not_a_readable_command_is_not_read_only(command):
    assert is_read_only_command(command) is False
